	[[nodiscard]] constexpr const Lines* Find(uint16_t npcId) noexcept
	{
		for (const auto& l : kLines)
			if (l.npcId == npcId) return &l;
		return nullptr;
	}

	[[nodiscard]] constexpr int TalkCount(uint16_t npcId) noexcept
	{
		const Lines* l = Find(npcId);
		int n = 0;
		if (l) for (const char* t : l->talk) if (t != nullptr) ++n;
		return n;
	}

	[[nodiscard]] constexpr int BarkCount(uint16_t npcId) noexcept
	{
		const Lines* l = Find(npcId);
		int n = 0;
		if (l) for (const char* t : l->barks) if (t != nullptr) ++n;
		return n;
	}
